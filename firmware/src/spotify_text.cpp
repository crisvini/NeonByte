bool composeSpotifyTextRow(std::string_view text, std::uint16_t offset, std::uint8_t row,
                           std::uint16_t color, std::uint8_t* output,
                           std::size_t outputCapacity) {
    if (output == nullptr || outputCapacity < SPOTIFY_TEXT_ROW_BYTES ||
        row >= SPOTIFY_TEXT_ROW_HEIGHT || text.size() > SPOTIFY_TEXT_MAX_CODE_POINTS) {
        return false;
    }

    std::fill_n(output, SPOTIFY_TEXT_ROW_BYTES, std::uint8_t{0});
    const int textLeft = 8 - static_cast<int>(offset);
    const int rowPixel = static_cast<int>(row / FONT_SCALE);
    if (rowPixel >= static_cast<int>(CLASSIC_FONT_HEIGHT)) return true;

    const int firstScreenX = std::max(0, textLeft);
    const int lastScreenX = std::min(
        static_cast<int>(SPOTIFY_TEXT_ROW_WIDTH),
        textLeft + static_cast<int>(text.size() * CLASSIC_CELL_WIDTH * FONT_SCALE));
    for (int screenX = firstScreenX; screenX < lastScreenX; ++screenX) {
        const unsigned sourceX = static_cast<unsigned>(screenX - textLeft);
        const unsigned characterIndex = sourceX / (CLASSIC_CELL_WIDTH * FONT_SCALE);
        const unsigned cellColumn = (sourceX / FONT_SCALE) % CLASSIC_CELL_WIDTH;
        if (cellColumn >= CLASSIC_FONT_WIDTH) continue;

        const auto inputCharacter = static_cast<unsigned char>(text[characterIndex]);
        const std::uint8_t character =
            inputCharacter >= FIRST_PRINTABLE_ASCII && inputCharacter <= LAST_PRINTABLE_ASCII
                ? inputCharacter
                : static_cast<std::uint8_t>('?');
        const std::size_t glyphOffset =
            static_cast<std::size_t>(character - FIRST_PRINTABLE_ASCII) * CLASSIC_FONT_WIDTH +
            cellColumn;
        const std::uint8_t column = pgm_read_byte(&CLASSIC_ASCII_FONT[glyphOffset]);
        if ((column & (1U << rowPixel)) == 0) continue;

        const auto pixelOffset = static_cast<std::size_t>(screenX) * 2;
        output[pixelOffset] = static_cast<std::uint8_t>(color);
        output[pixelOffset + 1] = static_cast<std::uint8_t>(color >> 8);
    }
    return true;
}

